uint64_t Crc64(const void* data, size_t len, uint64_t init) {
  uint64_t crc = init;
  const auto* p = static_cast<const uint8_t*>(data);
  for (size_t i = 0; i < len; i++) {
    crc = kCrc64Table[static_cast<uint8_t>(crc ^ p[i])] ^ (crc >> 8);
  }
  return crc;
}

